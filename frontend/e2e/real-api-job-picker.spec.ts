import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

test.use({ timezoneId: "UTC" });
for (const width of [390, 320]) {
  test(`header job picker and last-job protection use real API data at ${width}px`, async ({page,request}, testInfo) => {
    const origin = "http://127.0.0.1:4317";
    const signup = await request.post(`${origin}/api/auth/signup`, {data:{name:"Header Review",email:`header-${randomUUID()}@example.com`,password:"Header-review-strong-password-2026!",rate:35,workLocationName:"City Retail"}});
    expect(signup.status()).toBe(201);
    const {token} = await signup.json();
    const headers = {Authorization:`Bearer ${token}`,"X-Client-Time-Zone":"UTC"};
    const job = (await (await request.get(`${origin}/api/jobs`,{headers})).json()).jobs[0];
    const added = await request.post(`${origin}/api/jobs`, {headers,data:{name:"Harbour Hotel",rate:40}});
    expect(added.status()).toBe(201);
    const second = (await added.json()).job;
    const errors:string[]=[];
    page.on("pageerror",error=>errors.push(error.message));
    await page.route("**/api/**",async route=>{
      const url=new URL(route.request().url());
      await route.fulfill({response:await route.fetch({url:`${origin}${url.pathname}${url.search}`})});
    });
    await page.addInitScript(value=>{localStorage.setItem("wageTracker.token",value);localStorage.setItem("wageTracker.lastActivity",String(Date.now()));},token);
    await page.setViewportSize({width,height:width===320?568:844});
    await page.emulateMedia({colorScheme:width===390?"dark":"light"});
    await page.goto("/");
    const header=page.locator(".app-nav");
    const trigger=header.getByRole("button",{name:"Switch job. Current: City Retail",exact:true});
    await expect(trigger).toBeVisible();
    const box=await trigger.boundingBox();
    expect(box!.width).toBeLessThanOrEqual(44);
    await expect(header.locator(".app-nav-current-job")).toHaveText("City Retail");
    await trigger.click();
    const picker=page.getByRole("dialog",{name:"Switch job",exact:true});
    await expect(picker).toBeVisible();
    await expect(picker.getByRole("button",{name:"Manage jobs",exact:true})).toBeInViewport();
    const placement=await picker.boundingBox(), nav=await header.boundingBox();
    expect(placement!.y).toBeGreaterThanOrEqual(nav!.y+nav!.height);
    expect(placement!.x).toBeGreaterThanOrEqual(0);
    expect(placement!.x+placement!.width).toBeLessThanOrEqual(width);
    await picker.evaluate(element => Promise.all(element.getAnimations({subtree:true}).map(animation=>animation.finished)));
    await page.screenshot({path:testInfo.outputPath(`header-picker-${width}.png`)});
    await picker.getByRole("button",{name:/Harbour Hotel/}).click();
    await expect(header.locator(".app-nav-current-job")).toHaveText("Harbour Hotel");
    await expect(picker).toBeHidden();
    await page.getByRole("navigation",{name:"Main"}).getByRole("button",{name:"Settings",exact:true}).click();
    await expect(header.locator(".workspace-trigger")).toHaveCount(0);
    await page.getByRole("button",{name:/Your jobs/}).click();
    await page.getByRole("button",{name:"Delete City Retail",exact:true}).click();
    const review=page.getByRole("dialog",{name:"Delete this job?",exact:true});
    await review.getByRole("textbox").fill("City Retail");
    await review.getByRole("button",{name:"Delete job & data",exact:true}).click();
    await expect(review).toBeHidden();
    await page.getByRole("button",{name:"Delete Harbour Hotel",exact:true}).click();
    const warning=page.getByRole("dialog",{name:"Keep one job to continue",exact:true});
    await expect(warning).toContainText("Nothing has been deleted.");
    await expect(warning.getByRole("textbox")).toHaveCount(0);
    await expect(warning.getByRole("button",{name:"Add another job",exact:true})).toBeInViewport();
    await warning.evaluate(element => Promise.all(element.getAnimations({subtree:true}).map(animation=>animation.finished)));
    await page.screenshot({path:testInfo.outputPath(`last-job-warning-${width}.png`)});
    const blocked=await request.delete(`${origin}/api/jobs/${second.id}`,{headers,data:{confirmationName:second.name}});
    expect(blocked.status()).toBe(409);
    expect((await blocked.json()).code).toBe("LAST_JOB_REQUIRED");
    const remaining=(await (await request.get(`${origin}/api/jobs`,{headers})).json()).jobs;
    expect(remaining.map((entry:{id:string})=>entry.id)).toEqual([second.id]);
    await warning.getByRole("button",{name:"Add another job",exact:true}).click();
    const editor=page.getByRole("dialog",{name:"Add another job",exact:true});
    await expect(editor.getByLabel("Job or employer name",{exact:true})).toBeVisible();
    await editor.getByLabel("Job or employer name",{exact:true}).fill("Replacement job");
    await editor.getByLabel("Hourly rate (AUD)",{exact:true}).fill("30");
    await editor.getByRole("button",{name:"Create job",exact:true}).click();
    await expect(editor).toBeHidden();
    expect((await request.delete(`${origin}/api/jobs/${second.id}`,{headers,data:{confirmationName:second.name}})).status()).toBe(200);
    const finalJobs=(await (await request.get(`${origin}/api/jobs`,{headers})).json()).jobs;
    expect(finalJobs).toHaveLength(1);expect(finalJobs[0].name).toBe("Replacement job");
    expect(finalJobs[0].id).not.toBe(job.id);
    expect(errors).toEqual([]);
  });
}
